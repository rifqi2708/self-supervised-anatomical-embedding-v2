def source_path(original, root=None):
    """Resolve source members, retaining explicit older-checkout support.

    Current-checkout signature lookup never silently falls back to a shim.
    An explicitly supplied external checkout may still have the frozen legacy
    layout; use its original member when the canonical member is absent.
    """
    base = ROOT if root is None else Path(root)
    canonical = base / SOURCE_PATHS.get(original, original)
    if root is not None and not canonical.exists():
        return base / original
    return canonical
